"""Solver overlap analysis — which tasks are solved by multiple solvers, which uniquely?

Produces the paper's §5.1 "solver diversity" figure data. For each pair of solvers,
computes how many tasks are solved by (a) both, (b) only A, (c) only B. This
quantifies the diversity that an ensemble has to work with.

Writes experiments/results/solver_overlap.json and a markdown matrix.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from src.eval.loader import TRAIN_DIR, load_split  # noqa: E402
from src.eval.scorer import score_submission  # noqa: E402
from src.solvers import (  # noqa: E402
    AxisMirrorSolver,
    BoxSolver,
    CellularAutomatonSolver,
    ColorCountSolver,
    ColorMapSolver,
    CompositionSolver,
    D8Solver,
    DiffSolver,
    DimSolver,
    FrameSolver,
    GridDivideSolver,
    HistogramSolver,
    IdentitySolver,
    InductionSolver,
    LineSolver,
    MovementSolver,
    MultiRadiusInductionSolver,
    ObjectIsolationSolver,
    PeriodicityRepairSolver,
    PropagationSolver,
    RowColInductionSolver,
    SizeColorSolver,
    SubgridSolver,
    SymmetrySolver,
    TilingSolver,
    TransformSolver,
)


def main() -> None:
    solvers = {
        "identity": IdentitySolver(),
        "d8": D8Solver(),
        "color_map": ColorMapSolver(),
        "symmetry": SymmetrySolver(),
        "tiling": TilingSolver(),
        "object": ObjectIsolationSolver(),
        "induction": InductionSolver(radius=1),
        "multi_ind": MultiRadiusInductionSolver(radii=(0, 1, 2)),
        "line": LineSolver(),
        "color_count": ColorCountSolver(),
        "diff": DiffSolver(),
        "frame": FrameSolver(),
        "periodicity": PeriodicityRepairSolver(),
        "rowcol": RowColInductionSolver(),
        "ca": CellularAutomatonSolver(),
        "histogram": HistogramSolver(),
        "dim": DimSolver(),
        "subgrid": SubgridSolver(),
        "propagation": PropagationSolver(),
        "size_color": SizeColorSolver(),
        "movement": MovementSolver(),
        "box": BoxSolver(),
        "grid_divide": GridDivideSolver(),
        "axis_mirror": AxisMirrorSolver(),
        "transform": TransformSolver(),
        "composition": CompositionSolver(),
    }
    tasks = list(load_split(TRAIN_DIR))
    print(f"analyzing {len(tasks)} train tasks across {len(solvers)} solvers")

    solved: dict[str, set[str]] = {}
    for name, solver in solvers.items():
        preds = {t.task_id: solver.solve(t).candidates for t in tasks}
        s = score_submission(tasks, preds)
        solved[name] = {r.task_id for r in s.per_task if r.solved}
        print(f"  {name:<14s} solved {len(solved[name]):4d}")

    # Pairwise overlap
    names = list(solvers)
    pair_matrix: dict[str, dict[str, dict[str, int]]] = {}
    for a in names:
        pair_matrix[a] = {}
        for b in names:
            pair_matrix[a][b] = {
                "both": len(solved[a] & solved[b]),
                "only_a": len(solved[a] - solved[b]),
                "only_b": len(solved[b] - solved[a]),
                "union": len(solved[a] | solved[b]),
            }

    # Markdown matrix: rows=a, cols=b, cell=both|only_a
    lines = [
        "<!-- Auto-generated by scripts/solver_overlap_analysis.py -->",
        "### Pairwise solver overlap (train split, 1000 tasks)",
        "",
        "Each cell `x / y` = (solved by both) / (solved by row-solver but not col-solver)",
        "",
        "| \\ |" + "|".join(f" {n} " for n in names) + "|",
        "|---|" + "|".join("---" for _ in names) + "|",
    ]
    for a in names:
        row = [f"| **{a}** |"]
        for b in names:
            p = pair_matrix[a][b]
            if a == b:
                row.append(f" {len(solved[a])} |")
            else:
                row.append(f" {p['both']}/{p['only_a']} |")
        lines.append("".join(row))

    # Unique tasks per solver (solved by this one only)
    lines.extend(["", "### Unique tasks (solved by this solver, none of the others)", ""])
    lines.append("| Solver | Unique | Solves |")
    lines.append("|--------|-------:|-------:|")
    others_union: dict[str, set[str]] = {}
    for name in names:
        others = set()
        for b in names:
            if b != name:
                others |= solved[b]
        unique = solved[name] - others
        others_union[name] = unique
        lines.append(f"| {name} | {len(unique)} | {len(solved[name])} |")

    union_all = set()
    for s in solved.values():
        union_all |= s
    lines.extend(["", f"**Oracle union (any solver solves): {len(union_all)} / {len(tasks)}**"])

    out_dir = ROOT / "paper" / "tables"
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "solver_overlap.md").write_text("\n".join(lines) + "\n")

    raw = ROOT / "experiments" / "results"
    raw.mkdir(parents=True, exist_ok=True)
    (raw / "solver_overlap.json").write_text(
        json.dumps(
            {
                "per_solver_solved": {n: sorted(s) for n, s in solved.items()},
                "pair_matrix": pair_matrix,
                "oracle_union": sorted(union_all),
                "oracle_size": len(union_all),
            },
            indent=2,
        )
    )
    print(f"\nwrote paper/tables/solver_overlap.md + experiments/results/solver_overlap.json")
    print(f"oracle union: {len(union_all)} / {len(tasks)}")


if __name__ == "__main__":
    main()
