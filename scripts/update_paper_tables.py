"""Regenerate the paper's §5 tables from the latest experiments/results/*.json files.

Running this ensures every number in paper/main.md matches experimental JSON
output exactly. Called as part of `make paper` or manually before commit.

Writes snippets to `paper/tables/` for inclusion in main.md.
"""
from __future__ import annotations

import glob
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "experiments" / "results"
TABLES = ROOT / "paper" / "tables"
TABLES.mkdir(parents=True, exist_ok=True)


def latest(glob_pattern: str) -> Path | None:
    files = sorted(glob.glob(str(RESULTS / glob_pattern)))
    return Path(files[-1]) if files else None


def write_baseline_table() -> None:
    path = latest("baseline_*.json")
    if path is None:
        print("no baseline_*.json found — skip")
        return
    data = json.loads(path.read_text())
    rows = {}  # solver_name -> {'train': n, 'eval': n, 'total_eval': 120, 'total_train': 1000}
    for r in data:
        rows.setdefault(r["solver"], {})[r["split"]] = r
    lines = [
        "<!-- Auto-generated by scripts/update_paper_tables.py -->",
        "| Solver | train (1000) | eval (120) | ms/task |",
        "|--------|-------------:|-----------:|--------:|",
    ]
    for name in [
        "identity_solver",
        "d8_solver",
        "color_map_solver",
        "symmetry_solver",
        "tiling_solver",
        "object_isolation_solver",
        "transform_solver",
        "composition_solver",
        "ensemble_6_diverse_plain",
        "ensemble_6_diverse_verified",
        "ensemble_8_with_transform_comp_plain",
        "ensemble_8_with_transform_comp_verified",
    ]:
        train = rows.get(name, {}).get("train")
        ev = rows.get(name, {}).get("eval")
        if not train or not ev:
            continue
        lines.append(
            f"| {name} | {train['solved']}/{train['total']} ({train['accuracy']*100:.2f}%) | "
            f"{ev['solved']}/{ev['total']} ({ev['accuracy']*100:.2f}%) | "
            f"{ev['ms_per_task']:.1f} |"
        )
    out = TABLES / "baseline_table.md"
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out}")


def write_taxonomy_table() -> None:
    path = RESULTS / "taxonomy_summary.json"
    if not path.exists():
        print("no taxonomy_summary.json — skip")
        return
    summary = json.loads(path.read_text())
    lines = [
        "<!-- Auto-generated by scripts/update_paper_tables.py -->",
        "| Family | Eval (120) | Train (1000) |",
        "|--------|-----------:|-------------:|",
    ]
    eval_row = next(r for r in summary if r["split"] == "eval")
    train_row = next(r for r in summary if r["split"] == "train")
    all_fams = set(eval_row["family_distribution"]) | set(train_row["family_distribution"])
    for fam in sorted(all_fams):
        ec = eval_row["family_distribution"].get(fam, 0)
        tc = train_row["family_distribution"].get(fam, 0)
        lines.append(
            f"| {fam} | {ec} ({ec/eval_row['total']*100:.1f}%) | "
            f"{tc} ({tc/train_row['total']*100:.1f}%) |"
        )
    out = TABLES / "taxonomy_table.md"
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out}")


def write_oracle_table() -> None:
    path = RESULTS / "oracle_upper_bound.json"
    if not path.exists():
        print("no oracle_upper_bound.json — skip")
        return
    data = json.loads(path.read_text())
    lines = [
        "<!-- Auto-generated by scripts/update_paper_tables.py -->",
        "### Oracle upper bound (union of all heuristic solvers)",
        "",
        "| Split | Oracle solved | Tasks | Oracle accuracy |",
        "|-------|--------------:|------:|----------------:|",
    ]
    for split in ("eval", "train"):
        s = data[split]
        lines.append(
            f"| {split} | {s['oracle_union_size']} | {s['total_tasks']} | "
            f"{s['oracle_accuracy']*100:.2f}% |"
        )
    out = TABLES / "oracle_table.md"
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out}")


def main() -> None:
    write_baseline_table()
    write_taxonomy_table()
    write_oracle_table()
    print(f"\ntables in {TABLES}/")


if __name__ == "__main__":
    main()
